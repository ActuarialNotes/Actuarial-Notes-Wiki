#!/usr/bin/env python3
"""The CAS's published pass marks -> quiz/src/data/casPassMarks.json.

The CAS printed each sitting's total points, pass mark and 95th / 75th
percentiles in one PDF per exam, linked from its Past Exams & Pass Marks page,
until computer-based testing began in Fall 2020. This script downloads those
PDFs (cached outside the repo), records each file's sha256, and reads the
table mechanically. Nothing is typed by hand: re-run it, never edit the JSON.

    python3 scripts/cas_pass_marks.py [--cache DIR] [--offline] [--check]

--check reads the PDFs and fails if the committed JSON differs from them.
Used by the Practice Exam debrief (docs/practice-exam-debrief.md).
PyMuPDF is imported lazily, as in pdf_extract.py.
"""

from __future__ import annotations

import argparse
import datetime as dt
import hashlib
import json
import os
import re
import sys
import urllib.request

INDEX_URL = 'https://www.casact.org/exams-admissions/exam-results/past-exams-pass-marks'
BASE = 'https://www.casact.org/sites/default/files/2021-02/admissions_passmarks_'

# Bank label (Question.exam) -> the CAS's file for that exam.
EXAMS = {
    'Exam MAS-I': 'exammas-i',
    'Exam MAS-II': 'exammas-ii',
    'Exam 5': 'exam5',
    'Exam 6C': 'exam6c',
    'Exam 6U': 'exam6u',
    'Exam 7': 'exam7',
    'Exam 8': 'exam8',
    'Exam 9': 'exam9',
}

OUT = os.path.join(os.path.dirname(__file__), '..', 'quiz', 'src', 'data', 'casPassMarks.json')
SITTING = re.compile(r'^(Spring|Fall)\s+(\d{4})$')
NUMBER = re.compile(r'^\d+(?:\.\d+)?$')
# The date each PDF prints at its foot ("11 March 2019", "17July2012"), after the last row.
FOOTER_DATE = re.compile(r'^\d{1,2}\s*[A-Z][a-z]+\s*\d{4}$')


def fetch(url: str, cache: str, offline: bool) -> bytes:
    path = os.path.join(cache, url.rsplit('/', 1)[-1])
    if not os.path.exists(path):
        if offline:
            raise SystemExit(f'not cached: {url}')
        with urllib.request.urlopen(url, timeout=60) as r:  # noqa: S310 (fixed casact.org URLs)
            data = r.read()
        with open(path, 'wb') as f:
            f.write(data)
    with open(path, 'rb') as f:
        return f.read()


def pdf_lines(data: bytes) -> list[str]:
    import pymupdf  # lazy: the rest of scripts/ stays importable without it
    doc = pymupdf.open(stream=data, filetype='pdf')
    text = '\n'.join(page.get_text() for page in doc)
    return [ln.strip() for ln in text.splitlines() if ln.strip()]


def number(token: str) -> float | None:
    if token in ('--', '-', '—', '–'):
        return None
    if NUMBER.match(token):
        return float(token)
    raise ValueError(f'not a figure: {token!r}')


def parse_table(lines: list[str]) -> list[dict]:
    """Rows of the table: a sitting line, then total, pass mark, 95th, 75th, then comments.

    PyMuPDF gives one cell per line; a row ends where the next sitting begins.
    """
    rows: list[dict] = []
    starts = [i for i, ln in enumerate(lines) if SITTING.match(ln)]
    for k, i in enumerate(starts):
        end = starts[k + 1] if k + 1 < len(starts) else len(lines)
        cells = lines[i + 1:end]
        if len(cells) < 4:
            raise ValueError(f'short row at {lines[i]!r}: {cells}')
        session, year = SITTING.match(lines[i]).groups()
        total, pass_mark, p95, p75 = (number(c) for c in cells[:4])
        if total is None or pass_mark is None:
            raise ValueError(f'no total or pass mark at {lines[i]!r}')
        rest = cells[4:]
        if k + 1 == len(starts) and rest and FOOTER_DATE.match(rest[-1]):
            rest = rest[:-1]
        comment = ' '.join(rest).strip()
        row = {'session': session, 'year': int(year), 'totalPoints': total, 'passMark': pass_mark}
        if p95 is not None:
            row['percentile95'] = p95
        if p75 is not None:
            row['percentile75'] = p75
        if comment:
            row['comment'] = comment
        rows.append(row)
    if not rows:
        raise ValueError('no sittings found')
    return rows


def build(cache: str, offline: bool, read: str) -> dict:
    exams = {}
    for label, slug in EXAMS.items():
        url = f'{BASE}{slug}.pdf'
        data = fetch(url, cache, offline)
        exams[label] = {
            'source': url,
            'sha256': hashlib.sha256(data).hexdigest(),
            'sittings': parse_table(pdf_lines(data)),
        }
    return {
        '_note': 'Generated by scripts/cas_pass_marks.py from the CAS PDFs. Do not edit by hand.',
        'index': INDEX_URL,
        'read': read,
        'exams': exams,
    }


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.split('\n')[0])
    ap.add_argument('--cache', default=os.path.expanduser('~/.cache/actuarial-notes/cas-pass-marks'))
    ap.add_argument('--offline', action='store_true')
    ap.add_argument('--check', action='store_true')
    args = ap.parse_args(argv)
    os.makedirs(args.cache, exist_ok=True)
    if args.check:
        with open(OUT) as f:
            committed = json.load(f)
        fresh = build(args.cache, args.offline, committed['read'])
        if fresh != committed:
            print('casPassMarks.json differs from the CAS PDFs; re-run the script', file=sys.stderr)
            return 1
        print('casPassMarks.json matches the CAS PDFs')
        return 0
    out = build(args.cache, args.offline, dt.date.today().isoformat())
    with open(OUT, 'w') as f:
        json.dump(out, f, indent=2)
        f.write('\n')
    print(f'wrote {sum(len(e["sittings"]) for e in out["exams"].values())} sittings to {os.path.normpath(OUT)}')
    return 0


if __name__ == '__main__':
    sys.exit(main())
